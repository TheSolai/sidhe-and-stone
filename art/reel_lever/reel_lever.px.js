// The Fate Reel's pull lever.
//
// This is a hero prop: it is animated in the game, so its silhouette has to
// read at a glance, before any of the colour is read.
//
// The silhouette is three things, in one diagonal line: a flared brass grip
// at the top-left, an oak arm running down to the right, and a cast mount
// at the bottom-right that the arm is pivoted on. The whole lever leans up
// and to the left, which is the "at rest" position — the eye reads it as
// something that wants to be pulled DOWN, because the grip is up high and
// the pivot is down low. Turn the whole thing over and it would read as
// something to push up instead.
//
// The flared cap on the grip is the important part of the silhouette: it is
// wider than the shaft of the grip, so at 1x the eye sees a mushroom you
// put your hand on, and not a ball on a stick.
//
// The grip is brass, so it runs the gold ramp: H is the lit top of the
// cap, G is the body of it, and Y is the shadowed right and lower edge,
// the side the gallery light never reaches. The arm and the mount are dark
// oak and cast iron: Z is the lit top-left face of the beam, N is the body
// of it, and D is the deep shadow the mount sits in. So the two materials
// separate at a glance even at 1x, and the whole prop is lit from the same
// top-left as every other object in the museum.
//
// The hard D along the bottom of the mount is what stops the lever
// floating: it looks bolted to the floor of the reel chamber.

