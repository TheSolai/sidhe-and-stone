// The moon: a waxing crescent, opening to the right.
//
// The shape is an outer disc with a smaller disc taken out of it and pushed
// to the right, so what is left is a crescent with a rounded back on the
// left and a concave bite on the right. Drawing the bite is the whole
// trick: without the inner disc the shape is a circle, and a circle is not
// a moon.
//
// The colours are the ARCANE ramp, E, carried on a D shadow, with X for
// the sunlit rim: X is the lit upper-left edge where the light catches the
// outer curve, E is the body of the moon, and D is the shadowed concave
// edge on the inside of the crescent.
//
// The old version had the ramp running backwards - E for the lit rim and
// L for the body, so the lit edge was DARKER than the surface beside it -
// it pulled D, a warm brown, into an arcane object, and it used I, which
// the palette does not allow in a sprite at all. Now the ramp only ever
// steps one way, the moon is unambiguously arcane, and every key in it is
// one the palette actually offers.

