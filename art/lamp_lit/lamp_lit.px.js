// A lit brass oil lamp.
//
// The gallery's own light source, and the one object in the game that is
// allowed to be the brightest thing on screen.
//
// The silhouette is a flame on a short wick over a squat brass reservoir,
// and it is the flame that carries the read. The fire is built in three
// temperatures: W is the white-hot core, H is the body of the flame, and Y
// is the soft halo around it. The flame is a teardrop, narrow at the tip
// and wide where it leaves the wick, so at 1x it reads as fire and not as
// a lamp-shaped lightbulb.
//
// That halo is the whole point of the sprite — it is the only unfocused
// light in the set, and it is what says "this lamp is burning" before the
// eye has resolved any of the brass.
//
// The brass is the material ramp AYGH: G is the body of it, H is the lit
// top-left face, Y is the shadowed right edge, and the reservoir sits in a
// hard D along its foot.
//
// The flame is offset to the LEFT of the reservoir, so the brightest pixels
// land in the top-left quadrant where the light in this game comes from,
// and everything below and to the right falls away into Y and D. So the
// lamp is lit from the same side as every other object in the museum, and
// it is also the thing in the room that is casting that light.

