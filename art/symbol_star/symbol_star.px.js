// The star: five points, and it must be five. A four-pointed sparkle is a
// different symbol and it will read as a compass rose.
//
// The old version was a flat crossbar with two stilts standing under it,
// which read as a signpost rather than as a star. This one is a real
// five-pointed silhouette: a solid top point, two wide side points, and
// two splayed legs at the bottom with a clear notch cut between them.
//
// The light is global, not per-edge: the whole upper-left of the sprite is
// H, the whole lower-right is Y, and G is the body between them. G is the
// gold of the star, H the lit gold, Y the gold in shadow. Every point of
// the star points up-left into the light, so the whole shape turns the
// same way.

sprite("symbol_star", { w: 16, h: 16, outline: "K" },
  `
  .......H........
  ......HGH.......
  ......HGY.......
  .....HGGGH......
  ...HHGGGGGHH....
  HHHGGGGGGGGGHHH.
  .HGGGGGGGGGGGY..
  ..HGGGGGGGGGY...
  ...HGGGGGGGY....
  ...HGGGGGGGY....
  ...HGGGGGGGY....
  ...HGGYYYGGY....
  ...HYY...HYY....
  ...H.......H....
  ................
  ................
`)
