// The star: five points, and it must be five. A four-pointed sparkle is a
// different symbol and it will read as a compass rose.
//
// The old version was a flat crossbar with two stilts standing under it,
// which read as a signpost rather than as a star. This one is a real
// five-pointed silhouette, drawn solid: a filled body with a point on top,
// two wide points at the sides and two splayed legs below, with a clear
// notch cut between the legs. Every point is two pixels thick, so the
// shape still reads as a star when it is a hand tall.
//
// The light is per-edge, not global: the faces that turn up and to the
// left take H, the lit gold; the faces that turn down and to the right
// fall into Y, the gold in shadow; and G, the gold of the body, holds
// everything between them. The whole shape turns the same way, so the
// star sits in the same light as every other object in the museum.
sprite("symbol_star", { w: 16, h: 16, outline: "K" },
  `
  ................
  ......HH........
  ......HH........
  .....HHHH.......
  ....HHGGHH......
  HHHHHGGGGYYYYY..
  .HHGGGGGGGGYY...
  ..HHGGGGGGYY....
  ...HGGGGGGY.....
  ...HGGGGGGY.....
  ...HGYYYYGY.....
  ...YYY..YYY.....
  ...Y......Y.....
  ................
  ................
  ................
`)
