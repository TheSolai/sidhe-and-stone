// The honey: a full drop, fat at the top and tapering to a point at the
// bottom, so it reads as falling.
//
// G is the body of the honey, H is the gloss along the upper-left curve
// and down the lit side, and Y is the shadowed lower-right where the
// drop turns away from the light. The shadow wraps the right edge
// instead of stopping partway, which is what gives the drop its round.
//
// The point at the bottom trails into a Y drip, so the drop reads as
// honey on its way down rather than as a flat gold bead.
