// The clover: the luck symbol, and the only green thing on the reel.
//
// Four lobes meeting at a centre, each lobe a rounded blob rather than a
// circle, so the silhouette says "clover" and not "four dots". The lobes
// are separated by thin N veins so the eye reads four leaves and not one
// green splodge. The upper-left lobes are tipped with X — the sunlit side —
// and the veins run down into N, which is the shadow under the leaf.
sprite("symbol_clover", { w: 16, h: 16, outline: "K" },
  `
  ................
  ................
  ......MMMM......
  .....XMMNM......
  ....XMMMMMN.....
  ....XMMMNMMN....
  .....NMMMMN.....
  ......NMMN......
  .....NMMMMN.....
  ....XMMMNMMN....
  ....XMMMMMN.....
  .....XMMNM......
  ......MNM.......
  .......N........
  ................
  ................
`
)
